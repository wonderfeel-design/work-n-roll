"""Excel report (Person 2, Task 5).

    build_report(path=None) -> path of the .xlsx      (bot /report: send it as a document; web: /api/report.xlsx)

The sample workbook is the template, so tabs, column order, colours, dropdowns and formulas match it:
blue = values from the database, black = formulas, green = cross-tab lookups (Parcels_DUN, Vocabulary).
Formula columns are detected from the template's first data row and copied down, so the template stays
the single place that defines the layout. Excel / Numbers / LibreOffice calculate them on open.
"""
import datetime as dt
import re
from copy import copy
from pathlib import Path

from openpyxl import load_workbook
from openpyxl.formula.translate import Translator
from openpyxl.worksheet.worksheet import Worksheet

from app import DATA_DIR, db
from app.seed import SAMPLE_XLSX

EXPORT_DIR = DATA_DIR / "exports"
LOOKUP_ROWS = 500  # lookup ranges reach this far, so new parcels or vocabulary terms keep resolving

# The template's lookups stop at its last sample row (e.g. Vocabulary!$A$2:$A$19); widen them
_RANGE_END = re.compile(r"((?:Vocabulary|Parcels_DUN)!\$[A-Z]+\$2:\$[A-Z]+\$)\d+")


def _formula(cell) -> str | None:
    v = cell.value
    v = getattr(v, "text", v)  # ArrayFormula -> its text
    return v if isinstance(v, str) and v.startswith("=") else None


def _header(ws: Worksheet) -> list[str]:
    # "dose_per_ha (unit/ha)" -> "dose_per_ha"
    return [str(c.value).split(" (")[0] if c.value is not None else "" for c in ws[1]]


def _fill(ws: Worksheet, rows: list[dict]) -> None:
    """Replace the template's example rows with ours, keeping each column's style and formula."""
    header = _header(ws)
    template = list(ws[2])[: len(header)]
    styles = [copy(c._style) for c in template]
    formulas = [_RANGE_END.sub(rf"\g<1>{LOOKUP_ROWS}", f) if (f := _formula(c)) else None for c in template]
    if ws.max_row > 1:
        ws.delete_rows(2, ws.max_row - 1)
    for r, data in enumerate(rows, start=2):
        for col, (name, style, formula) in enumerate(zip(header, styles, formulas), start=1):
            cell = ws.cell(row=r, column=col)
            cell._style = copy(style)
            if formula:
                origin = f"{cell.column_letter}2"
                cell.value = Translator(formula, origin=origin).translate_formula(cell.coordinate)
            else:
                cell.value = data.get(name)
    if ws.auto_filter.ref:
        ws.auto_filter.ref = f"A1:{ws.cell(row=1, column=len(header)).column_letter}{max(len(rows) + 1, 2)}"


def _local(ts: str | None) -> dt.datetime | None:
    """ISO timestamp with offset -> naive Madrid time (Excel has no time zones)."""
    if not ts:
        return None
    return dt.datetime.fromisoformat(ts).astimezone(db.TZ).replace(tzinfo=None)


def _log_rows() -> list[dict]:
    parcels = {p["alias"]: p for p in db.get_parcels()}
    rows = []
    for rec in reversed(db.list_records(limit=100_000)):  # oldest first, like the sample
        d = rec.model_dump()
        d["record_id"] = f"R{rec.id:04d}"
        d["date"] = dt.date.fromisoformat(rec.date) if rec.date else None
        # Treated area: what the farmer said, else the whole parcel (same rule as the console's dose/ha)
        if d["area_ha"] is None and rec.parcel_alias in parcels:
            d["area_ha"] = parcels[rec.parcel_alias]["area_ha"]
        rows.append(d)
    return rows


def _correction_rows(record_ids: list[int]) -> list[dict]:
    rows = []
    for rid in record_ids:
        for c in db.corrections_for(rid):
            rows.append({**c, "record_id": f"R{rid:04d}", "timestamp": _local(c["timestamp"]),
                         "used_as_fewshot": "yes" if c["used_as_fewshot"] else "no"})
    return sorted(rows, key=lambda c: c["id"])


def build_report(path: str | None = None) -> str:
    wb = load_workbook(SAMPLE_XLSX)

    parcels = [{**p, "parcel_alias": p["alias"], "spoken_names": "; ".join(p["spoken_names"])}
               for p in db.get_parcels()]
    _fill(wb["Parcels_DUN"], parcels)
    _fill(wb["Vocabulary"], db.get_vocabulary())

    log = _log_rows()
    _fill(wb["Field_Log"], log)
    _fill(wb["Corrections"], _correction_rows([int(r["record_id"][1:]) for r in log]))

    readme = wb["README"]
    readme["A2"] = (f"Generated by Field Voice on {dt.datetime.now(db.TZ):%Y-%m-%d %H:%M} (Europe/Madrid) "
                    f"from the live database: {len(log)} records.")
    wb.calculation.fullCalcOnLoad = True

    if path is None:
        EXPORT_DIR.mkdir(parents=True, exist_ok=True)
        path = str(EXPORT_DIR / f"field_log_{dt.datetime.now(db.TZ):%Y%m%d_%H%M%S}.xlsx")
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    wb.save(path)
    return path


if __name__ == "__main__":
    print(build_report())
